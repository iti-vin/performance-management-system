-- ============================================================================
-- 14. Users (authentication)
-- Matches the backend TypeORM entities `UserRole` and `User`
-- (backend/src/modules/auth/entities/user-role.entity.ts, user.entity.ts).
-- Load after employees.sql: pms.users references pms.employees.
-- ============================================================================

-- Stores named role codes. The codes are ROLE_CODES in @pms/shared-types; id 1 is the admin role.
CREATE TABLE IF NOT EXISTS pms.user_role (
    id          bigint PRIMARY KEY,
    code        text NOT NULL UNIQUE,
    name        text NOT NULL UNIQUE,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

-- Stores the PMS login of an employee, its role, and the temporary login lock state.
CREATE TABLE IF NOT EXISTS pms.users (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id            bigint NOT NULL REFERENCES pms.employees(id),
    user_role_id           bigint NOT NULL REFERENCES pms.user_role(id),
    email                  text NOT NULL UNIQUE,
    username               text NOT NULL UNIQUE,
    password_hash          text NOT NULL,
    failed_login_attempts  integer NOT NULL DEFAULT 0,
    login_locked_until     timestamptz,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS users_employee_id_idx ON pms.users (employee_id);
CREATE INDEX IF NOT EXISTS users_user_role_id_idx ON pms.users (user_role_id);
