-- Moves the auth data from public to pms, for the backend entities that now read pms.
-- Run it once, yourself, with psql against the PMS database. Nothing runs it automatically.
--
--   psql "<your connection>" -v ON_ERROR_STOP=1 -f packages/database/migrations/2026-11-24-auth-tables-to-pms.sql
--
-- BEFORE YOU RUN IT: replace every REPLACE_ME value in step 2 with real directory values.
-- public.employees has no company, department, branch, or employment status, and pms.employees
-- requires all four. The guard at the end of step 2 stops the script while a REPLACE_ME is left.
--
-- What it changes:
--   1. Creates pms.user_role (as in schema/identity-and-directory.sql) and copies public.user_role.
--   2. Copies public.employees into pms.employees (same id and guid).
--   3. Drops pms.users ONLY WHEN IT IS EMPTY (it still has the old uuid shape), creates it again
--      as in schema/users.sql, and copies public.users with the same ids and password hashes.
-- It leaves public.user_role, public.employees, and public.users as they are.
-- Everything runs in one transaction: any error leaves the database unchanged.

BEGIN;

-- 1. Roles ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pms.user_role (
    id          bigint PRIMARY KEY,
    code        text NOT NULL,
    name        text NOT NULL UNIQUE,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

INSERT INTO pms.user_role (id, code, name, created_at, updated_at)
SELECT user_role_id, code, name, created_at, updated_at
FROM public.user_role
ON CONFLICT (id) DO NOTHING;

-- 2. Employees --------------------------------------------------------------
INSERT INTO pms.employees (
    guid, id, code, email, first_name, last_name, hrdotnet_id,
    company, department, branch, employment_status, status, created_at, updated_at
)
SELECT
    guid, id, code, email, first_name, last_name, hrdotnet_id,
    'REPLACE_ME_COMPANY',      -- company
    'REPLACE_ME_DEPARTMENT',   -- department
    'REPLACE_ME_BRANCH',       -- branch
    'regular',                 -- employment_status: one of probationary, regular, resigned, terminated,
                               -- contractual, end_of_contract, retired, separated
    status, created_at, updated_at
FROM public.employees
ON CONFLICT (id) DO NOTHING;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pms.employees
        WHERE company LIKE 'REPLACE_ME%' OR department LIKE 'REPLACE_ME%' OR branch LIKE 'REPLACE_ME%'
    ) THEN
        RAISE EXCEPTION 'Replace the REPLACE_ME values in step 2 before you run this script';
    END IF;
END $$;

-- 3. Users ------------------------------------------------------------------
DO $$
BEGIN
    IF to_regclass('pms.users') IS NOT NULL AND EXISTS (SELECT 1 FROM pms.users) THEN
        RAISE EXCEPTION 'pms.users has rows: stop, nothing is dropped';
    END IF;
END $$;

DROP TABLE IF EXISTS pms.users;

CREATE TABLE pms.users (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id            bigint NOT NULL REFERENCES pms.employees(id),
    user_role_id           bigint NOT NULL REFERENCES pms.user_role(id),
    email                  text NOT NULL UNIQUE,
    username               text NOT NULL UNIQUE,
    password_hash          text NOT NULL,
    failed_login_attempts  integer NOT NULL DEFAULT 0,
    login_locked_until     timestamptz,
    created_at             timestamptz NOT NULL DEFAULT now(),
    updated_at             timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX users_employee_id_idx ON pms.users (employee_id);
CREATE INDEX users_user_role_id_idx ON pms.users (user_role_id);

INSERT INTO pms.users (
    id, employee_id, user_role_id, email, username, password_hash,
    failed_login_attempts, login_locked_until, created_at, updated_at
)
SELECT
    id, employee_id, user_role_id, email, username, password_hash,
    failed_login_attempts, login_locked_until, created_at, updated_at
FROM public.users;

-- The next generated id must come after the copied ones.
SELECT setval(pg_get_serial_sequence('pms.users', 'id'), (SELECT COALESCE(max(id), 1) FROM pms.users));

COMMIT;
